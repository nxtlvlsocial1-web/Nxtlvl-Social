#!/usr/bin/env python3
"""Phrase subtitles for the long-form film -> src/subs-data.js.

Display text: column 3 of audio/vo-script.tsv (exact on-screen wording, digits and punctuation).
Times: whisper words in transcript.json, aligned with difflib; unmatched words are spread inside
their line's window. A phrase ends at punctuation or after 7 words.
"""
import difflib
import json
import re
from pathlib import Path

proj = Path(__file__).resolve().parent.parent
rows = [l.rstrip("\n").split("\t") for l in (proj / "audio" / "vo-script.tsv").read_text().splitlines() if l.strip()]
lines = json.loads((proj / "audio" / "vo-lines.json").read_text())["lines"]
whisper = json.loads((proj / "transcript.json").read_text())
norm = lambda w: re.sub(r"[^a-z0-9]", "", w.lower())

words = []  # {d: display, n, line, tag}
for (tag, _tts, disp), ln in zip(rows, lines):
    for w in disp.split():
        words.append({"d": w, "n": norm(w), "line": ln["line"], "tag": tag})
wn = [norm(x["text"]) for x in whisper]
times = [None] * len(words)
sm = difflib.SequenceMatcher(a=[w["n"] for w in words], b=wn, autojunk=False)
for a, b, size in sm.get_matching_blocks():
    for k in range(size):
        times[a + k] = (whisper[b + k]["start"], whisper[b + k]["end"])
win = {ln["line"]: (ln["start"], ln["end"]) for ln in lines}
i = 0
while i < len(words):
    if times[i] is not None:
        i += 1
        continue
    j = i
    while j < len(words) and times[j] is None and words[j]["line"] == words[i]["line"]:
        j += 1
    ls, le = win[words[i]["line"]]
    lo = times[i - 1][1] if i > 0 and words[i - 1]["line"] == words[i]["line"] and times[i - 1] else ls
    hi = times[j][0] if j < len(words) and words[j]["line"] == words[i]["line"] and times[j] else le
    step = max((hi - lo) / (j - i), 0.1)
    for k in range(j - i):
        times[i + k] = (lo + k * step, lo + (k + 1) * step)
    i = j
# clamp into line windows
for w, t in zip(words, times):
    ls, le = win[w["line"]]
    s, e = min(max(t[0], ls - 0.05), le), max(min(t[1], le + 0.1), t[0] + 0.05)
    w["s"], w["e"] = s, e

phrases, cur = [], []
def flush():
    if cur:
        phrases.append({"t": " ".join(x["d"] for x in cur), "s": cur[0]["s"], "e": cur[-1]["e"], "line": cur[0]["line"], "q": cur[0]["tag"] in ("L", "B")})
    cur.clear()
for k, w in enumerate(words):
    if cur and w["line"] != cur[-1]["line"]:
        flush()
    cur.append(w)
    end_punct = re.search(r"[.?!…]\"?$|\.\.\.$", w["d"])
    comma = w["d"].endswith(",") and len(cur) >= 4
    # words left until this sentence ends (same line): don't leave one or two words dangling
    left = 0
    for x in words[k + 1:]:
        if x["line"] != w["line"]:
            break
        left += 1
        if re.search(r"[.?!…,]\"?$", x["d"]):
            break
    if end_punct or comma or (len(cur) >= 7 and left > 2) or len(cur) >= 9:
        flush()
flush()
# timing: show slightly early, hold until the next phrase (max 0.6 s of tail), never overlap
for k, p in enumerate(phrases):
    p["s"] = round(max(0.0, p["s"] - 0.08), 3)
    nxt = phrases[k + 1]["s"] - 0.08 if k + 1 < len(phrases) else p["e"] + 0.6
    p["e"] = round(min(p["e"] + 0.6, max(nxt, p["s"] + 0.5)), 3)
    if k + 1 < len(phrases):
        p["e"] = min(p["e"], phrases[k + 1]["s"] - 0.08 + 0.0)
out = [{"t": p["t"].replace('"', "“", 1).replace('"', "”") if p["t"].count('"') == 2 else p["t"].replace('"', ""), "s": p["s"], "e": round(p["e"], 3), **({"q": 1} if p["q"] else {})} for p in phrases]
(proj / "src" / "subs-data.js").write_text("// generated by scripts/build-subs.py — do not edit by hand\nexport const SUBS = " + json.dumps(out) + ";\n")
print(len(out), "phrases; last ends", out[-1]["e"])
