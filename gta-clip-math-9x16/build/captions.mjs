// Caption timing for gta-clip-math-9x16. Single source for the on-screen captions and captions.srt.
//
//   node build/captions.mjs        (from the project root)
//
// Writes assets/js/captions.js (window.CAPS, read by index.html) and captions.srt.
// There is no voiceover, so each line is timed to its scene window from the owner's timing table,
// at a natural speaking pace (about 4.6 syllables a second, stretched up to 1.3x when the scene is long).
// If a voiceover is added later, replace the computed word times with real word timestamps.
//
// Markup: groups split on "|"; a leading * marks the accent word; {display=spoken} gives the spoken form
// of a number so its timing weight is right.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

// [scene start, scene end, lead-in, caption line]
const LINES = [
  [0.0, 3.0, 0.0, "A million-view | {GTA=gee tee ay} {6=six} clip | pays *{$225.=two hundred twenty five dollars}"],
  [3.0, 5.0, 0.12, "Not a *thousand."],
  [5.0, 7.0, 0.12, "Here's the *math | nobody shows you."],
  [7.0, 11.0, 0.15, "Dylan Page's campaign | pays *{$1=one dollar} | per *{1,000=thousand} views."],
  [11.0, 15.0, 0.12, "But every clip | is *capped | at *{$250.=two hundred fifty dollars}"],
  [15.0, 18.0, 0.12, "Then the platform | takes *{10%.=ten percent}"],
  [18.0, 21.0, 0.1, "So your clip | *stops earning | at *{250K=two hundred fifty thousand} views."],
  [21.0, 23.0, 0.12, "Now watch *this."],
  [23.0, 28.0, 0.15, "*{5=five} clips | at *{200K=two hundred thousand} views each."],
  [28.0, 32.0, 0.1, "Same million views. | That pays *{$900.=nine hundred dollars} | *{4x=four times} more."],
  [32.0, 34.0, 0.08, "So stop chasing | *one viral clip."],
  [34.0, 37.0, 0.08, "One *catch: | budgets run out *fast. | Check the campaign | page first."],
  [37.0, 39.45, 0.1, "Comment *MATH | and I'll send you | the full rate list."],
];

const SYL_PER_S = 4.6;
const MAX_STRETCH = 1.3;
const TAIL = 0.12; // breath before the next scene

function syllables(word) {
  const w = word.toLowerCase().replace(/[^a-z]/g, "");
  if (!w) return 1;
  let groups = (w.match(/[aeiouy]+/g) || []).length;
  if (w.length > 3 && w.endsWith("e") && !/[aeiouy]le$/.test(w) && !w.endsWith("ee")) groups -= 1;
  return Math.max(1, groups);
}

function parse(line) {
  return line.split("|").map((g) => {
    const toks = g.trim().match(/\*?\{[^}]+\}|\S+/g);
    return toks.map((t) => {
      const accent = t.startsWith("*");
      if (accent) t = t.slice(1);
      let display = t, spoken = t;
      const m = t.match(/^\{([^=]+)=([^}]+)\}$/);
      if (m) { display = m[1]; spoken = m[2]; }
      const syl = spoken.split(/[\s-]+/).reduce((a, w) => a + syllables(w), 0);
      const pause = /[.:,]$/.test(display) ? 1.6 : 0; // punctuation adds a short pause (in syllables)
      return { w: display, accent, weight: syl, pause };
    });
  });
}

const caps = [];
for (const [s, e, lead, text] of LINES) {
  const groups = parse(text);
  const words = groups.flat();
  const sylTotal = words.reduce((a, w) => a + w.weight + w.pause, 0) - words[words.length - 1].pause;
  const natural = sylTotal / SYL_PER_S;
  const avail = e - s - lead - TAIL;
  const dur = Math.min(avail, natural * MAX_STRETCH);
  const k = dur / sylTotal;
  let t = s + lead;
  const out = [];
  for (const g of groups) {
    const gw = [];
    for (const w of g) {
      const ws = t, we = t + w.weight * k;
      gw.push({ w: w.w, accent: w.accent, s: +ws.toFixed(3), e: +we.toFixed(3) });
      t = we + w.pause * k;
    }
    out.push(gw);
  }
  // each group stays up until the next group starts (within the scene), else for a beat after its last word
  out.forEach((gw, i) => {
    const next = out[i + 1];
    const last = gw[gw.length - 1].e;
    const end = next ? next[0].s : Math.min(e - 0.02, last + 1.1);
    caps.push({ s: gw[0].s, e: +end.toFixed(3), words: gw });
  });
}

writeFileSync(join(ROOT, "assets/js/captions.js"),
  "// generated by build/captions.mjs; edit the lines there, not here\nwindow.CAPS = " + JSON.stringify(caps) + ";\n");

const ts = (x) => {
  const ms = Math.round(x * 1000), h = Math.floor(ms / 3600000), m = Math.floor(ms / 60000) % 60, sec = Math.floor(ms / 1000) % 60;
  return `${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}:${String(sec).padStart(2, "0")},${String(ms % 1000).padStart(3, "0")}`;
};
const srt = caps.map((c, i) => `${i + 1}\n${ts(c.s)} --> ${ts(c.e)}\n${c.words.map((w) => w.w).join(" ")}\n`).join("\n");
writeFileSync(join(ROOT, "captions.srt"), srt);

