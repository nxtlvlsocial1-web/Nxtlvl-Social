// Builds the caption track for the Clip Math reel from build/captions.json:
//  1. writes out/captions.srt (one cue per 2-4 word chunk, plain text, no accent marks)
//  2. injects the word timings into index.html between the CAPTIONS markers
// Run from the project root: node build/captions.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.dirname(path.dirname(new URL(import.meta.url).pathname));
const data = JSON.parse(fs.readFileSync(path.join(root, "build/captions.json"), "utf8"));

const ts = (t) => {
  const ms = Math.round(t * 1000);
  const h = Math.floor(ms / 3600000), m = Math.floor((ms % 3600000) / 60000), s = Math.floor((ms % 60000) / 1000);
  const p = (n, w = 2) => String(n).padStart(w, "0");
  return `${p(h)}:${p(m)}:${p(s)},${p(ms % 1000, 3)}`;
};

const chunks = data.chunks.map((c) => {
  const raw = c.t.split(" ");
  const words = raw.map((w) => ({ w: w.replace(/^[*^]/, ""), a: w[0] === "*" ? "p" : w[0] === "^" ? "o" : "" }));
  // word reveal times: explicit "at", else spread over the first 70% of the chunk (max 0.3 s apart)
  const step = Math.min(0.3, ((c.e - c.s) * 0.7) / Math.max(1, words.length));
  words.forEach((w, i) => (w.t = +(c.at ? c.at[i] : c.s + i * step).toFixed(3)));
  if (c.s === 0) words.forEach((w) => (w.t = 0)); // frame 0 already shows the first chunk
  return { s: c.s, e: c.e, screen: c.screen !== false, words };
});

// sanity: chunk words joined must reproduce the spoken script, numerals aside
const srt = chunks.map((c, i) => `${i + 1}\n${ts(c.s)} --> ${ts(c.e)}\n${c.words.map((w) => w.w).join(" ")}\n`).join("\n");
fs.mkdirSync(path.join(root, "out"), { recursive: true });
fs.writeFileSync(path.join(root, "out/captions.srt"), srt);

const html = path.join(root, "index.html");
const src = fs.readFileSync(html, "utf8");
const js = `/* CAPTIONS:BEGIN (generated by build/captions.mjs from build/captions.json; edit there) */\n      const CAPTIONS = ${JSON.stringify(chunks.filter((c) => c.screen))};\n      /* CAPTIONS:END */`;
const out = src.replace(/\/\* CAPTIONS:BEGIN[\s\S]*?CAPTIONS:END \*\//, js);
if (out === src && !src.includes(js)) throw new Error("CAPTIONS markers not found in index.html");
fs.writeFileSync(html, out);
console.log(`wrote out/captions.srt (${chunks.length} cues) and injected ${chunks.filter((c) => c.screen).length} on-screen chunks`);
