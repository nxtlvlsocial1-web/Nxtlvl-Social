"""Creators 100X "AI wrote this reel" (9:16, meta): writes index.html, plan/sfx_events.json and plan/edit.json.
The script is ChatGPT's own reply to the five-part prompt (word for word, see script.md); the voice is the owner's
ElevenLabs take (Jessica), line 1 made robotic by build/vo_robot.py. Two layers: the soft-3D scene (build/scene.js,
three.js, a pure function of time) and the DOM layer here (captions, labels, backdrops, the glitch), on one GSAP timeline.
python3 build/generate.py"""
import json
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fx import ROOT, LINES, L0, L1, T, JS, SFX, js, sfx, ft, to, st  # noqa: E402

random.seed(100)
DUR = round(L1["r6"] + 1.3, 2)
SW = round(L1["r0"] + .3, 3)                     # the AI-to-human switch (before "And honestly")
SW = min(SW, L0["r1"] - .08)
HTMLS = []

# ---------- word times for the 3D layer ----------
C = {
    "sw": SW, "r2": L0["r2"], "r3": L0["r3"], "r4": L0["r4"], "r5": L0["r5"], "r6": L0["r6"], "end": DUR,
    "point": T("r1", "point"), "write": T("r2", "Write"), "scriptEnd": T("r2", "script") + .4, "send": T("r2", "script") + .5,
    "dont": T("r2", "don't"), "magic": T("r2", "magic"), "wall": T("r2", "You'll"), "posting": T("r2", "posting"),
    "mistake": T("r3", "mistake"), "task": T("r3", "giving") - .1, "not": T("r3", "not"), "direction": T("r3", "direction") + .08,
    "five": T("r4", "five"), "items": [T("r4", "role"), T("r4", "audience"), T("r4", "hook"), T("r4", "format"), T("r4", "tone")],
    "knows": T("r5", "knows"),
    "promptW": T("r6", "PROMPT"), "post": T("r6", "PROMPT") + .5, "dmIn": T("r6", "send") - .05, "nine": T("r6", "nine"),
}
C["hi"] = [[T("r5", "what")], [T("r5", "who")], [], [T("r5", "what") + .15], [T("r5", "how")]]
C["reply1"] = [[w["w"], w["t0"]] for w in LINES["r0"] + LINES["r1"]]
C["hops"] = [C["point"], C["magic"] + .1, C["mistake"], *C["items"], C["post"], C["nine"]]
C["spins"] = [SW + .02, C["knows"], C["r6"] - .1]
C["bumps"] = [C["dont"], C["direction"], *C["items"], C["post"], C["dmIn"] + .25]
C = {k: (round(v, 3) if isinstance(v, float) else v) for k, v in C.items()}


# ---------- captions: one band at the top, words blur in on their spoken time ----------
def head(hid, rows, line, size=80, after=0.0, robot=False, until=None):
    spoken = [w for w in LINES[line] if w["t0"] >= after - 1e-6]
    k, out, rws = 0, [], []
    for row in rows:
        ws = []
        for word in row:
            pk = word.startswith("*")
            word = word.lstrip("*")
            key = word.lower().strip('.,:!?"')
            t = None
            while k < len(spoken):
                sw = spoken[k]["w"].lower().strip('.,:!?"')
                k += 1
                if sw[:4] == key[:4]:
                    t = spoken[k - 1]["t0"]
                    break
            t = spoken[-1]["t0"] if t is None else t
            wid = f"{hid}w{len(out)}"
            ws.append(f'<span class="hw{" pk" if pk else ""}" id="{wid}">{word}</span>')
            out.append((wid, t))
        rws.append(f'<div class="hl">{" ".join(ws)}</div>')
    HTMLS.append(f'<div class="head{" rb" if robot else ""}" id="{hid}" style="font-size:{size}px">{"".join(rws)}</div>')
    for wid, t in out:
        ft(f"#{wid}", t - .05, .32, "{opacity: 0, y: 30, scale: .9, filter: 'blur(10px)'}", "{opacity: 1, y: 0, scale: 1, filter: 'blur(0px)'}", "back.out(2)")
    if until is not None:
        to(f"#{hid}", until - .2, .2, "{opacity: 0, y: -30, filter: 'blur(10px)'}", "power2.in")


head("h0", [["This", "reel", "was"], ["written", "by", "*ChatGPT."]], "r0", 84, robot=True, until=SW + .05)
head("h1", [["And", "honestly,"], ["that's", "the", "*point."]], "r1", 92, until=L0["r2"])
head("h2a", [["If", "you", "type,"], ['"Write', "me", "a", "reel", 'script,"'], ["don't", "expect", "*magic."]], "r2", 76, until=C["wall"])
head("h2b", [["You'll", "get", "the", "same"], ["*generic", "content"], ["everyone", "else", "is", "posting."]], "r2", 78, after=C["wall"], until=L0["r3"])
head("h3", [["The", "*mistake?"], ["You're", "giving", "AI", "a", "task,"], ["not", "*direction."]], "r3", 80, until=L0["r4"])
head("h4", [["Give", "it", "*five", "things:"]], "r4", 92, until=T("r4", "role") - .02)
# the five things as a running caption under the band while the blocks land
head("h4b", [["its", "*role,", "your", "*audience,"], ["your", "*hook", "rule,", "your", "*format,"], ["and", "your", "*tone."]], "r4", 64,
     after=T("r4", "its") - .05, until=L0["r5"])
head("h5", [["Now", "ChatGPT", "knows"], ["*who", "it's", "writing", "for,"], ["*what", "to", "say,", "and", "*how", "to", "say", "it."]], "r5", 70, until=L0["r6"])
head("h6", [["Comment", "*PROMPT"], ["and", "I'll", "send", "you", "the", "full"], ["prompt", "plus", "*nine", "more."]], "r6", 76)

# ---------- status pill ----------
PILLS = [(0, "GENERATED BY AI", "rb"), (SW + .1, "CHATGPT WROTE THIS", ""), (L0["r2"], "THE LAZY PROMPT", ""), (C["wall"] + .3, "SAME AS EVERYONE", "pk"),
         (L0["r3"], "THE MISTAKE", "pk"), (L0["r4"], "THE 5-PART PROMPT", "lm"), (L0["r5"], "WHAT IT NOW KNOWS", "lm"), (L0["r6"], "FREE PDF IN YOUR DMS", "pk")]
for i, (t, txt, cls) in enumerate(PILLS):
    HTMLS.append(f'<div class="stat {cls}" id="st{i}"><span>{txt}</span></div>')
    end = PILLS[i + 1][0] if i + 1 < len(PILLS) else DUR + 1
    if t <= 0:
        js(f'gsap.set("#st{i}", {{opacity: 1}});')
    else:
        ft(f"#st{i}", t, .3, "{opacity: 0, scale: .6, y: -10}", "{opacity: 1, scale: 1, y: 0}", "back.out(3)")
    if end < DUR:
        to(f"#st{i}", end - .12, .12, "{opacity: 0, scale: .9}", "power2.in")

# ---------- backdrops: the robot room, the glitch, the Creators 100X studio ----------
js('gsap.set("#bgB", {clipPath: "circle(0% at 50% 52%)"});')
ft("#bgB", SW - .02, .5, "{clipPath: 'circle(0% at 50% 52%)'}", "{clipPath: 'circle(150% at 50% 52%)'}", "power3.inOut")
to("#scan", SW, .25, "{opacity: 0}")
for k in range(9):
    tk = SW - .32 + k * .045
    HTMLS.append(f'<i class="gl" id="gl{k}" style="top:{random.randint(200, 1700)}px;height:{random.randint(14, 80)}px;'
                 f'background:{random.choice(("#fd0b68", "#ccfb79", "#ffffff", "#3ad1ff"))}"></i>')
    js(f'tl.fromTo("#gl{k}", {{opacity: 0, x: {random.randint(-300, 300)}}}, {{keyframes: [{{opacity: .9, x: 0, duration: .03}}, '
       f'{{opacity: .9, x: {random.randint(-200, 200)}, duration: .05}}, {{opacity: 0, duration: .03}}], immediateRender: false}}, {tk:.3f});')
js(f'tl.fromTo("#gl3d", {{filter: "none", x: 0}}, {{keyframes: ['
   f'{{filter: "hue-rotate(90deg) saturate(3)", x: -18, duration: .05}}, {{filter: "invert(1)", x: 14, duration: .04}}, {{filter: "none", x: -8, duration: .05}}, '
   f'{{filter: "hue-rotate(-60deg) saturate(2)", x: 10, duration: .05}}, {{filter: "none", x: 0, duration: .06}}], immediateRender: false}}, {SW - .25:.3f});')
ft("#flash", SW, .35, "{opacity: .9}", "{opacity: 0}", "power2.out")
# glows drift
js(f'tl.fromTo("#bgB .glo", {{x: 0, y: 0, scale: 1}}, {{x: (i) => [80, -70, 60, -90][i], y: (i) => [60, -80, -50, 70][i], scale: (i) => [1.15, .9, 1.1, .95][i], '
   f'duration: {DUR / 2:.2f}, yoyo: true, repeat: 1, ease: "sine.inOut", immediateRender: false}}, 0);')
# a pink flash on the crack and on "Post"
for t in (C["direction"], C["post"]):
    ft("#flash", t, .25, "{opacity: .55}", "{opacity: 0}", "power2.out")

# ---------- the 3D layer follows the timeline: a setter tween that calls window.__render3 ----------
js(f'(() => {{ let cur = 0; const R = {{ t(v) {{ if (v === undefined) return cur; cur = v; window.__render3 && window.__render3(v); }} }}; '
   f'tl.fromTo(R, {{t: 0}}, {{t: {DUR:.2f}, duration: {DUR:.2f}, ease: "none", immediateRender: false}}, 0); }})();')

# ---------- sound ----------
for w in LINES["r0"]:
    sfx("typing", w["t0"])
sfx("glitch", SW - .3)
sfx("glitch", SW - .1)
sfx("impact", SW)
sfx("whoosh_big", SW + .02)
sfx("sparkle", C["point"])
sfx("whoosh", L0["r2"] - .1)
for k in range(0, len("Write me a reel script"), 3):
    sfx("typing", C["write"] + k * (C["scriptEnd"] - C["write"]) / 22)
sfx("click", C["send"])
sfx("pop", C["dont"])
sfx("sparkle", C["magic"] - .05)
sfx("error", C["magic"] + .45)
sfx("riser_short", C["wall"] - .1)
for k in range(6):
    sfx("pop", C["wall"] + .15 + k * .25)
sfx("buzzer", C["posting"])
sfx("paper", C["mistake"])
sfx("whoosh", C["mistake"] + .2)
sfx("thump", C["task"] + .25)
sfx("glitch", C["not"])
sfx("impact", C["direction"])
sfx("scratch", C["direction"] + .05)
sfx("ding2", C["five"])
for t in C["items"]:
    sfx("latch", t - .02)
    sfx("whoosh", t - .3)
sfx("sparkle", C["knows"])
for t in (T("r5", "who"), T("r5", "what"), T("r5", "how")):
    sfx("ping", t)
sfx("whoosh_big", L0["r6"] - .35)
sfx("pop", L0["r6"] - .15)
for k in range(6):
    sfx("typing", C["promptW"] + k * .065)
sfx("click", C["post"])
sfx("whoosh", C["post"] + .15)
sfx("ding", C["dmIn"] + .3)
for k in range(9):
    sfx("flip", C["nine"] - .05 + k * .05) if k % 3 == 0 else None
sfx("chime", C["nine"] + .3)

CSS = open(os.path.join(ROOT, "build", "style.css")).read()
SCENE = open(os.path.join(ROOT, "build", "scene.js")).read()
html = f"""<!doctype html>
<html lang="en" data-resolution="portrait">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <title>Creators 100X: AI wrote this reel 9x16</title>
    <script src="assets/vendor/gsap.min.js"></script>
    <style>{CSS}</style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{DUR:.2f}" data-fps="30" data-width="1080" data-height="1920">
      <div class="bg" id="bgA"></div><div class="bg" id="scan"></div>
      <div class="bg" id="bgB"><i class="glo" style="left:-260px;top:-240px;background:radial-gradient(circle,rgba(206,251,143,.95),rgba(206,251,143,0) 70%)"></i>
        <i class="glo" style="right:-300px;top:-200px;background:radial-gradient(circle,rgba(254,112,179,.75),rgba(254,112,179,0) 70%)"></i>
        <i class="glo" style="left:-300px;bottom:-220px;background:radial-gradient(circle,rgba(254,112,179,.7),rgba(254,112,179,0) 70%)"></i>
        <i class="glo" style="right:-260px;bottom:-260px;background:radial-gradient(circle,rgba(206,251,143,.9),rgba(206,251,143,0) 70%)"></i></div>
      <canvas id="gl3d" width="1080" height="1920"></canvas>
      {chr(10).join(HTMLS)}
      <div id="flash"></div><div id="grain"></div>
    </div>
    <script>
      window.__hf = window.__hf || {{}}; window.__hf.buildReady = window.__hf.buildReady || {{}};
      window.__hf.buildReady.scene3d = new Promise((r) => {{ window.__sceneReady = r; }});
      window.__timelines = window.__timelines || {{}};
      const tl = gsap.timeline({{paused: true}});
      {chr(10).join("      " + j for j in JS).strip()}
      tl.set({{}}, {{}}, {DUR:.2f});
      tl.progress(1, true).progress(0, true);
      window.__timelines["main"] = tl;
    </script>
    <script type="module">
const C = {json.dumps(C)};
{SCENE}
    </script>
  </body>
</html>
"""
open(os.path.join(ROOT, "index.html"), "w").write(html)
SFX.sort(key=lambda e: e["t"])
json.dump(SFX, open(os.path.join(ROOT, "plan", "sfx_events.json"), "w"), indent=0)
json.dump({"dur": DUR, "music_in": round(SW, 3), "lines": L0}, open(os.path.join(ROOT, "plan", "edit.json"), "w"), indent=1)
print(f"wrote index.html: {DUR:.2f} s, switch {SW:.2f} s, {len(JS)} timeline lines, {len(SFX)} sfx")
