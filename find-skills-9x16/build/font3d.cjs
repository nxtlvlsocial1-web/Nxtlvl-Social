// Converts Barlow Condensed 900 (SIL OFL) into a Three.js typeface JSON for the extruded 3D numbers and words.
//   node build/font3d.cjs <path-to-opentype.js>      (from the project root; opentype.js 1.3.4 from npm)
// Reads build/barlow-condensed-latin-900-normal.woff, writes assets/fonts/bc900.typeface.json (only the glyphs used)
// and the same data as an ES module, assets/js/bc900-font.js, which scene3d.js imports (no fetch at render time).
const fs = require('fs'), path = require('path');
const opentype = require(process.argv[2] || 'opentype.js');
const ROOT = path.join(__dirname, '..');
const font = opentype.parse(fs.readFileSync(path.join(__dirname, 'barlow-condensed-latin-900-normal.woff')).buffer);
const CHARS = "0123456789$,.%KMx\u00d7\u2212-=?!'#+/ ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz";
const r = (v) => Math.round(v * 10) / 10;
const glyphs = {};
for (const ch of CHARS) {
  const g = font.charToGlyph(ch);
  const p = g.getPath(0, 0, font.unitsPerEm);
  const o = [];
  for (const c of p.commands) {
    // opentype paths are y-down; typeface JSON is y-up. q/b list the end point first, then the control points.
    if (c.type === 'M') o.push('m', r(c.x), r(-c.y));
    else if (c.type === 'L') o.push('l', r(c.x), r(-c.y));
    else if (c.type === 'Q') o.push('q', r(c.x), r(-c.y), r(c.x1), r(-c.y1));
    else if (c.type === 'C') o.push('b', r(c.x), r(-c.y), r(c.x1), r(-c.y1), r(c.x2), r(-c.y2));
  }
  const bb = g.getBoundingBox();
  glyphs[ch] = { ha: Math.round(g.advanceWidth), x_min: Math.round(bb.x1), x_max: Math.round(bb.x2), o: o.join(' ') };
}
const out = {
  glyphs, familyName: 'Barlow Condensed Black', ascender: font.ascender, descender: font.descender,
  underlinePosition: font.tables.post.underlinePosition, underlineThickness: font.tables.post.underlineThickness,
  boundingBox: { xMin: font.tables.head.xMin, yMin: font.tables.head.yMin, xMax: font.tables.head.xMax, yMax: font.tables.head.yMax },
  resolution: font.unitsPerEm, capHeight: font.tables.os2.sCapHeight || 700,
  original_font_information: { license: 'SIL Open Font License 1.1', source: 'Barlow Condensed by Jeremy Tribby' },
};
fs.writeFileSync(path.join(ROOT, 'assets/js/bc900-font.js'), '// generated by build/font3d.cjs from Barlow Condensed 900 (SIL OFL 1.1)\nexport default ' + JSON.stringify(out) + ';\n');
console.log('glyphs', Object.keys(glyphs).length, 'unitsPerEm', font.unitsPerEm, 'capHeight', out.capHeight);
