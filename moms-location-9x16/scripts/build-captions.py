#!/usr/bin/env python3
"""Align script words to whisper word timings -> src/captions-data.js.

Usage: python3 build-captions.py <project_dir>
Display words come from audio/vo-lines.txt (exact script); times from transcript.json.
Style follows the reference: lowercase, punctuation stripped except apostrophes.
"""
import difflib
import json
import re
import sys
from pathlib import Path

proj = Path(sys.argv[1])
lines = json.loads((proj / "audio" / "vo-lines.json").read_text())["lines"]
whisper = json.loads((proj / "transcript.json").read_text())

norm = lambda w: re.sub(r"[^a-z0-9]", "", w.lower())
# show spoken numbers as digits (punchier on screen, and whisper writes them that way)
DIGITS = {"twelve": "12", "thirty": "30", "thirty-nine": "39", "forty-seven": "47", "forty-eight": "48", "forty-nine": "49"}
script = []  # (display, norm, line_no)
for ln in lines:
    for w in ln["text"].split():
        disp = re.sub(r"[^\w'\-]", "", w).lower()
        disp = DIGITS.get(disp, disp)
        if disp:
            script.append({"w": disp, "n": norm(disp), "line": ln["line"]})
# spoken phrases shown as one caption word (e.g. "three oh seven" -> "3:07")
PHRASES = [(["two", "fourteen"], "2:14")]
merged, i = [], 0
while i < len(script):
    for words, shown in PHRASES:
        if [t["w"] for t in script[i:i + len(words)]] == words:
            merged.append({"w": shown, "n": norm(shown), "line": script[i]["line"]})
            i += len(words)
            break
    else:
        merged.append(script[i])
        i += 1
script = merged
wn = [norm(x["text"]) for x in whisper]
sn = [s["n"] for s in script]

times = [None] * len(script)
sm = difflib.SequenceMatcher(a=sn, b=wn, autojunk=False)
for a, b, size in sm.get_matching_blocks():
    for k in range(size):
        times[a + k] = (whisper[b + k]["start"], whisper[b + k]["end"])

# unmatched words: spread evenly inside their line's window between known neighbours
line_win = {ln["line"]: (ln["start"], ln["end"]) for ln in lines}
i = 0
while i < len(script):
    if times[i] is not None:
        i += 1
        continue
    j = i
    while j < len(script) and times[j] is None:
        j += 1
    lo = times[i - 1][1] if i > 0 else line_win[script[i]["line"]][0]
    hi = times[j][0] if j < len(script) else line_win[script[j - 1]["line"]][1]
    lo = max(lo, line_win[script[i]["line"]][0]) if script[i]["line"] != (script[i - 1]["line"] if i else 0) else lo
    n = j - i
    step = max((hi - lo) / n, 0.12)
    for k in range(n):
        times[i + k] = (lo + k * step, lo + (k + 1) * step)
    i = j

# keep words inside their own line window (whisper drifts a little at pauses)
words = []
for s, (st, en) in zip(script, times):
    ls, le = line_win[s["line"]]
    st = min(max(st, ls - 0.05), le)
    en = max(min(en, le + 0.1), st + 0.08)
    words.append({"w": s["w"], "s": round(st, 3), "e": round(en, 3), "line": s["line"]})

# every word gets at least 70 ms on screen (whisper sometimes stacks two words on one timestamp)
for k in range(1, len(words)):
    if words[k]["s"] < words[k - 1]["s"] + 0.07:
        words[k]["s"] = round(words[k - 1]["s"] + 0.07, 3)
        words[k]["e"] = max(words[k]["e"], words[k]["s"] + 0.08)

# each word shows until the next starts; across a long pause it clears 0.35 s after it ends
for k, w in enumerate(words):
    nxt = words[k + 1]["s"] if k + 1 < len(words) else w["e"] + 0.6
    w["off"] = round(min(nxt, max(w["e"] + 0.35, w["s"] + 0.25)) if nxt - w["e"] > 0.6 else nxt, 3)

out = proj / "src" / "captions-data.js"
out.write_text("// generated by scripts/build-captions.py — do not edit by hand\nexport const WORDS = "
               + json.dumps([{k: w[k] for k in ("w", "s", "off")} for w in words]) + ";\n")
unmatched = sum(1 for k in range(len(script)) if sm and times[k] is None)
print(f"{len(words)} caption words -> {out}")
